from __future__ import annotations

from datetime import datetime, timezone

from ..version import AUTHOR, AUTHOR_INITIALS, ORGANIZATION, PRODUCT_NAME, __version__
from .base import BaseReporter


class MarkdownReporter(BaseReporter):
    name = "markdown"
    extension = "md"

    def render(self) -> str:
        report = self.report
        out = []
        add = out.append
        add("# %s Security Assessment Report" % PRODUCT_NAME)
        add("")
        add("**Author / Maintainer:** %s (%s)  " % (AUTHOR, AUTHOR_INITIALS))
        add("**Generated by:** %s v%s - %s  " % (PRODUCT_NAME, __version__, ORGANIZATION))
        add("**Started:** %s  " % report.started_at)
        add("**Finished:** %s  " % report.finished_at)
        add("**Duration:** %.1fs" % report.duration)
        add("**Scan ID:** %s" % report.scan_id)
        add("**Risk score:** %s/100 - %s" % (report.risk_score, report.posture))
        add("")
        add("## Target")
        add("")
        add("| Field | Value |")
        add("| --- | --- |")
        if report.target:
            add("| Input | `%s` |" % report.target.input)
            add("| Base URL | `%s` |" % report.target.base_url)
            add("| Hostname | `%s` |" % (report.target.hostname or "-"))
            add("| IP | `%s` |" % (report.target.ip or "-"))
            add("| Root domain | `%s` |" % (report.target.root_domain or "-"))
        add("")
        add("## Scanner coverage")
        add("")
        add("| Scanner | Status | Findings | Duration | Note |")
        add("| --- | --- | --- | --- | --- |")
        for res in report.results:
            add("| %s | %s | %d | %.1fs | %s |" % (res.scanner, res.status.value, res.finding_count, res.duration, (res.error or "-").replace("|", "/")[:60]))
        add("")
        add("## Findings")
        add("")
        for f in self.ordered_findings():
            add("### [%s] %s" % (f.severity.value.upper(), f.title))
            add("")
            add("- Category: %s" % f.category)
            add("- Target: %s" % f.target)
            add("")
            if f.description:
                add(f.description)
                add("")
            if f.evidence:
                add(f.evidence[:1200])
                add("")
            if f.remediation:
                add("**Remediation:** %s" % f.remediation)
                add("")
        add("")
        stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
        add("_Generated by %s v%s - built by %s (%s) on %s._" % (PRODUCT_NAME, __version__, AUTHOR, AUTHOR_INITIALS, stamp))
        add("")
        return "\n".join(out)


__all__ = ["MarkdownReporter"]
